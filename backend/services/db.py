"""
Postgres access shared by the backend: connection, schema, writer lock.

The database lives on the pi4 and is reached over Tailscale. Mac and PC never
write at the same time; the writer lock is what enforces that, because the rule
alone is not enough (a second backend would close the first host's open session).
"""

import os
from contextlib import contextmanager
from pathlib import Path

import psycopg
from dotenv import load_dotenv

ENV_FILE = Path(__file__).parent.parent / ".env"
load_dotenv(ENV_FILE)

WRITER_LOCK_KEY = "z21_writer"

# Three outcomes, not two: "the database is unreachable" is not "another host owns
# the writer lock", and treating them alike made a 30-second outage look like a
# lost lock: events dropped and the session re-created.
WRITER_HOLDING = "holding"
WRITER_OTHER = "other"
WRITER_UNREACHABLE = "unreachable"

_writer_conn: psycopg.Connection | None = None


def database_url() -> str:
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError(
            f"DATABASE_URL not set (expected in {ENV_FILE}). "
            "Start the database with 'cd deploy && docker compose up -d' and copy "
            "deploy/.env.example to backend/.env, or point DATABASE_URL at an existing "
            "PostgreSQL 17 instance: see docs/DATABASE_POSTGRES.md."
        )
    return url


def describe() -> str:
    """Where we are connected, for the startup log: host and database, never the password."""
    from urllib.parse import urlsplit
    try:
        parts = urlsplit(database_url())
        return f"{parts.hostname}:{parts.port or 5432}/{parts.path.lstrip('/')}"
    except (RuntimeError, ValueError):
        return "DATABASE_URL not set"


def get_connection(autocommit: bool = True, timeout: int = 2) -> psycopg.Connection:
    """Fresh connection, short timeout: an unreachable host must not stall a request."""
    return psycopg.connect(database_url(), autocommit=autocommit, connect_timeout=timeout)


@contextmanager
def connection(**kwargs):
    """Short-lived connection, closed on exit: no pool until a measurement asks for one."""
    conn = get_connection(**kwargs)
    try:
        yield conn
    finally:
        conn.close()


def acquire_writer_lock() -> bool:
    """
    Take the process-wide writer lock, held for as long as this process lives.

    Returns False when another host already holds it: this instance then serves
    reads and must not create, close or delete sessions.
    """
    global _writer_conn
    if _writer_conn is not None:
        return True
    conn = psycopg.connect(database_url(), autocommit=True, connect_timeout=2,
                           options="-c statement_timeout=2000")
    got = conn.execute("SELECT pg_try_advisory_lock(hashtext(%s))", (WRITER_LOCK_KEY,)).fetchone()[0]
    if not got:
        conn.close()
        return False
    _writer_conn = conn
    return True


def is_writer() -> bool:
    return _writer_conn is not None and not _writer_conn.closed and not _writer_conn.broken


def ensure_writer_lock() -> str:
    """
    Re-check the lock without opening a connection when it is still healthy.

    A session-level advisory lock dies with its connection: a Postgres restart or a
    dropped tunnel leaves this process believing it is the writer while another host
    can take the lock. Called by the flush loop every ten seconds, and returns one of
    WRITER_HOLDING, WRITER_OTHER or WRITER_UNREACHABLE so the caller can tell an
    outage from a lost lock.
    """
    global _writer_conn
    if _writer_conn is not None and not (_writer_conn.closed or _writer_conn.broken):
        try:
            _writer_conn.execute("SELECT 1")
            return WRITER_HOLDING
        except psycopg.OperationalError:
            try:
                _writer_conn.close()
            except psycopg.Error:
                pass
            _writer_conn = None
            # The connection died, so the lock did too, but nothing says another host
            # took it: report the outage and try again on the next tick.
            return WRITER_UNREACHABLE
        except psycopg.Error:
            return WRITER_HOLDING

    _writer_conn = None
    try:
        return WRITER_HOLDING if acquire_writer_lock() else WRITER_OTHER
    except psycopg.Error:
        return WRITER_UNREACHABLE


