# Additive changes, applied in order on every start. One database serves both
# develop and main, so nothing here drops or renames: a column that goes away
# would break the branch that has not moved yet.
MIGRATIONS = [
    "ALTER TABLE locomotive_speed_table ADD COLUMN IF NOT EXISTS vstart integer",
    "ALTER TABLE locomotive_speed_table ADD COLUMN IF NOT EXISTS vhigh integer",
    "ALTER TABLE locomotive_speed_table ADD COLUMN IF NOT EXISTS decoder_type text",
]


def init_schema() -> None:
    """Create or extend the schema. Safe to run from both hosts at once."""
    with get_connection(autocommit=False) as conn:
        conn.execute("SELECT pg_advisory_xact_lock(hashtext('z21_init_schema'))")
        conn.execute(SCHEMA)
        for statement in MIGRATIONS:
            conn.execute(statement)
